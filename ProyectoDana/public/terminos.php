    <section class="seleccion-boletos">

        <h2>1. Participación</h2>
        <p>
            Al apartar o comprar boletos, el participante acepta las reglas de la rifa,
            las condiciones de pago y el método de selección del ganador indicado en cada rifa.
        </p>

        <h2>2. Apartado de boletos</h2>
        <p>
            Los boletos apartados permanecerán reservados por el tiempo indicado por administración.
            Si el participante no realiza el pago o no sube comprobante dentro del plazo establecido,
            los boletos podrán liberarse nuevamente.
        </p>

        <h2>3. Validación de pagos</h2>
        <p>
            Los boletos se consideran confirmados únicamente cuando el pago sea revisado y aprobado
            por administración. Mientras el pago esté pendiente, el boleto no se considera completamente validado.
        </p>

        <h2>4. Comprobantes</h2>
        <p>
            El participante deberá subir un comprobante válido de transferencia, depósito o pago.
            Administración podrá rechazar comprobantes ilegibles, duplicados, falsos o incorrectos.
        </p>

        <h2>5. Selección del ganador</h2>
        <p>
            El ganador será elegido conforme al método publicado en cada rifa. Este método puede estar
            basado en resultados oficiales, transmisión en vivo u otro mecanismo informado previamente.
        </p>

        <h2>6. Premios</h2>
        <p>
            El premio será entregado de acuerdo con la descripción de cada rifa. En caso de premios físicos,
            la entrega podrá coordinarse directamente con el ganador.
        </p>

        <h2>7. Datos personales</h2>
        <p>
            Los datos solicitados como nombre, WhatsApp y correo se usarán únicamente para registrar
            la participación, validar pagos, contactar al ganador y administrar la rifa.
        </p>

        <h2>8. Rifas con productos restringidos</h2>
        <p>
            En caso de rifas relacionadas con productos para adultos, alcohol u otros artículos restringidos,
            la participación podrá limitarse exclusivamente a personas mayores de edad.
        </p>

        <h2>9. Cancelaciones</h2>
        <p>
            Administración podrá cancelar una rifa por causa justificada. En ese caso, se informará a los
            participantes sobre el procedimiento correspondiente.
        </p>

        <h2>10. Aceptación</h2>
        <p>
            Al participar, el usuario declara haber leído y aceptado estos términos y condiciones.
        </p>

